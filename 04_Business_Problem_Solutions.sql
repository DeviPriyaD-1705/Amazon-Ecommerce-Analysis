/*
9. Payment Success Rate 

Calculate the percentage of successful payments across all orders.
Include breakdowns by payment status (e.g., failed, pending).
*/

SELECT 
     p.payment_status,
     COUNT(*) as total_count,
     ROUND(COUNT(*) / (SELECT COUNT(*) FROM payments) * 100, 2) AS percentage_of_successful_payments
FROM orders as o
JOIN payments as p
ON o.order_id = p.order_id
GROUP BY
     p.payment_status
ORDER BY
     percentage_of_successful_payments desc;

