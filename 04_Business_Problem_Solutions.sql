/*
5. Best-Selling Categories by State

Identify the best-selling product category for each state.
Include the total sales for that category within each state.
*/

SELECT *
FROM
(
	SELECT 
		 c.state,
		 cat.category_name,
		 SUM(oi.total_sales)  as total_sales,
		 RANK() OVER(PARTITION BY c.state ORDER BY SUM(oi.total_sales) desc) as rank_category_state_wise
	FROM orders as o
	JOIN customers as c
		ON o.customer_id = c.customer_id
	JOIN order_items as oi
		ON o.order_id = oi.order_id
	JOIN products as p
		ON oi.product_id = p.product_id
	JOIN category as cat
		ON p.category_id = cat.category_id
	GROUP BY
		  c.state,
		  cat.category_namE
) as ranked_state_wise
WHERE rank_category_state_wise = 1;

