/*
10. Product Profit Margin

Calculate the profit margin for each product sold (difference between price and cost of goods sold).
Rank products by their profit margin, showing highest to lowest.
*/

SELECT 
     p.product_id,
     p.product_name,
     SUM(oi.total_sales - (p.cogs * oi.quantity)) as profit,
     ROUND(SUM(oi.total_sales - (p.cogs * oi.quantity)) / SUM(oi.total_sales) *100,2) as profit_margin,
     DENSE_RANK() OVER(ORDER BY SUM(oi.total_sales - (p.cogs * oi.quantity)) / SUM(oi.total_sales) *100 desc) as rank_profit_margin
FROM order_items as oi
JOIN products as p
ON oi.product_id = p.product_id
GROUP BY
      p.product_id,
      p.product_name;

