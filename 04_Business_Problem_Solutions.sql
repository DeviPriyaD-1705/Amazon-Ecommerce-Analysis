/*
14. Top Performing Sellers

Find the top 5 sellers based on total sales value.
Include both successful and failed orders, display their percentage of successful orders.
*/

WITH top_sellers as
(
	SELECT 
		 s.seller_id,
		 s.seller_name,
		 ROUND(SUM(oi.total_sales),2) as total_sales 
	FROM orders as o
	JOIN sellers as s
	ON o.seller_id = s.seller_id
	JOIN order_items as oi
	ON o.order_id = oi.order_id
	GROUP BY
		   s.seller_id,
		   s.seller_name
	ORDER BY 
		   total_sales desc
	LIMIT 5
),
seller_order_status as
(
	SELECT 
         ts.seller_id,
         ts.seller_name,
		 o.order_status,
		 count(*) as total_orders
	FROM orders as o
  JOIN top_sellers as ts
    ON o.seller_id = ts.seller_id
  WHERE order_status not in  ('Inprogress','Returned')
	GROUP BY 
		   ts.seller_id, 
       ts.seller_name,
       o.order_status
)

SELECT 
	seller_id,
    seller_name,
    SUM(total_orders) as total_orders,
    SUM(CASE 
            WHEN order_status = 'Completed' THEN total_orders
            ELSE 0
        END) as successful_orders,
    SUM(CASE 
            WHEN order_status = 'Cancelled' THEN total_orders
            ELSE 0
        END) as failed_orders,
     ROUND(SUM(
            CASE 
                WHEN order_status = 'Completed' THEN total_orders
                ELSE 0
            END) / SUM(total_orders) * 100,2) as successful_order_percentage
FROM seller_order_status
GROUP BY
	   seller_id,
	   seller_name
ORDER BY seller_id;

