/*
13. Monthly Sales Trend

Query monthly total sales over the past year.
Display the sales trend, grouping by month, return current_month sale, last month sale
*/

SELECT 
    month,
    year,
    total_sales as current_month_sales,
    LAG(total_sales) OVER (ORDER BY year, month) as last_month_sales
FROM 
(
 SELECT 
     MONTH(o.order_date) AS month,
     YEAR(o.order_date) AS year,
     ROUND(SUM(oi.total_sales), 2) AS total_sales
 FROM orders as o
 JOIN order_items as oi
    ON o.order_id = oi.order_id
 GROUP BY 
     YEAR(o.order_date),
     MONTH(o.order_date)
) as monthly_sales
ORDER BY 
     year,
     month asc;

