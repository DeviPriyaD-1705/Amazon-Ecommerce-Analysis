/*
11. Most Returned Products

Query the top 10 products by the number of returns.
Display the return rate as a percentage of total units sold for each product.
*/

SELECT
     p.product_id,
	 p.product_name,
     COUNT(*) as total_orders,
     SUM(CASE
            WHEN o.order_status = 'Returned'
            THEN oi.quantity
            ELSE 0
        END) as returned_units,
	 SUM(oi.quantity) as total_units_sold,
     ROUND(SUM(CASE
                WHEN o.order_status = 'Returned'
                THEN oi.quantity
                ELSE 0
               END) / SUM(oi.quantity) * 100,2) as return_rate
FROM orders as o
JOIN order_items as oi
    ON o.order_id = oi.order_id
JOIN products as p
    ON oi.product_id = p.product_id
GROUP BY 
     p.product_id,
	 p.product_name
ORDER BY
    return_rate DESC
LIMIT 10;

