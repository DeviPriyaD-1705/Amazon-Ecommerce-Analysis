/*
12. Top 5 customers by orders in each state

Identify the top 5 customers with the highest number of orders by each state
Include the number of orders and total sales for each customers
*/

SELECT *
FROM
(
	SELECT 
		c.state,
		CONCAT(c.first_name,' ',c.last_name) as full_name,
		COUNT(quantity) as total_orders,
		SUM(oi.total_sales) as total_sales,
		DENSE_RANK() OVER(PARTITION BY c.state ORDER BY COUNT(quantity) desc) as rank_highest_order_state
	FROM customers as c
	JOIN orders as o
	ON o.customer_id = c.customer_id
	JOIN order_items as oi
	ON o.order_id = oi.order_id
	GROUP BY
		 c.state,
		 CONCAT(c.first_name,' ',c.last_name)
	ORDER BY
		  total_orders  desc
) as ranked_table
WHERE rank_highest_order_state <= 5;

