-- Applying Inner Join
SELECT 
      oi.product_id,
      p.product_name,
      SUM(oi.total_sales) as total_sales,
      SUM(oi.quantity) as total_quantity
FROM order_items as oi
JOIN orders as o
	ON oi.order_id = o.order_id
JOIN products as p
	ON oi.product_id = p.product_id
GROUP BY 
      oi.product_id,
      p.product_name
ORDER BY total_sales desc
LIMIT 10;

