/*
2. Revenue Contribution by Category

Find out how much revenue each product category generates
and what percentage of the overall revenue comes from each category.
*/

SELECT 
	 p.category_id,
     c.category_name, 
     ROUND(SUM(oi.total_sales),2) as total_sales,
	 ROUND(SUM(oi.total_sales) / 
            (
			 SELECT SUM(total_sales) 
             FROM order_items) * 100,2
            ) as percentage_contribution_by_each_category
FROM order_items as oi
JOIN products as p
	ON oi.product_id = p.product_id
JOIN category as c
	ON p.category_id = c.category_id
GROUP BY 
	 p.category_id,
     c.category_name
ORDER BY total_sales desc;

