/*
6. Customer Lifetime Value (CLTV)
(CLTV means total sales value generated by that customer over all their orders in your dataset.)

Calculate the total value of orders placed by each customer over their lifetime. 
Rank customers based on their CLTV
*/

SELECT 
     c.customer_id,
     CONCAT(c.first_name ,' ' , c.last_name) as full_name,
     ROUND(SUM(oi.total_sales),2) as cltv,
     DENSE_RANK() OVER(ORDER BY ROUND(SUM(oi.total_sales),2) desc) as rank_based_on_cltv
FROM orders as o
JOIN customers as c
	ON o.customer_id = c.customer_id
JOIN order_items as oi
	ON o.order_id = oi.order_id
GROUP BY
       c.customer_id,
       CONCAT(c.first_name ,' ' , c.last_name)
ORDER BY 
       cltv DESC;
       
