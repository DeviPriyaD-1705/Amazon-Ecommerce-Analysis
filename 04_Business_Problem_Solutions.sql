/*
8. Shipping Delays

Identify orders where the shipping date is later than 3 days after the order date.
Sort the results by shipping delay, from highest to lowest.
Include customer, order details, and delivery provider.
*/

SELECT 
    o.order_id,
    CONCAT(c.first_name, ' ', c.last_name) AS customer_name,
    o.order_date,
    s.shipping_date,
    s.shipping_providers,
    DATEDIFF(s.shipping_date, o.order_date) AS shipping_delays
FROM orders as o
JOIN customers as c
ON o.customer_id = c.customer_id
JOIN shipping as s
ON o.order_id = s.order_id
WHERE DATEDIFF(s.shipping_date, o.order_date) > 3
ORDER BY
      shipping_delays desc; 

